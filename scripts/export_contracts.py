#!/usr/bin/env python3
"""Generate (or verify) the language-neutral contract in ``contracts/``.

The schema is not hand-written: it is exported from the pydantic model that the
runtime actually uses, so it cannot drift from behaviour. ``--check`` regenerates
in memory and fails if the committed files are stale.

Usage:
    python scripts/export_contracts.py          # write contracts/
    python scripts/export_contracts.py --check  # CI / pre-commit
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
CONTRACTS = ROOT / "contracts"

sys.path.insert(0, str(ROOT))

from sms_wiz.models import (  # noqa: E402
    AppleAction,
    AppleSubAction,
    EntityKind,
    Intent,
    LedgerTreatment,
    Retention,
    SmsEvent,
)

ENUM_FILES = {
    "intents": [member.value for member in Intent],
    "apple_actions": [member.value for member in AppleAction],
    "apple_subactions": [member.value for member in AppleSubAction],
    "retentions": [member.value for member in Retention],
    "ledger_treatments": [member.value for member in LedgerTreatment],
    "entity_kinds": [member.value for member in EntityKind],
}


def build() -> dict[Path, str]:
    """Return ``{path: contents}`` for every generated contract file."""
    schema = SmsEvent.model_json_schema()
    schema["title"] = "SmsWizEvent"
    schema["$comment"] = (
        "Generated by scripts/export_contracts.py from sms_wiz.models.SmsEvent. "
        "Do not edit by hand; run `python scripts/export_contracts.py`."
    )
    enums = {
        "_comment": "Generated from the Python enums. Swift mirrors these raw values in "
        "ios/Packages/SMSCore/Sources/SMSCore/Contracts.swift; `make verify-contracts` enforces it.",
        **ENUM_FILES,
    }
    return {
        CONTRACTS / "sms_event.schema.json": json.dumps(schema, indent=2, sort_keys=True) + "\n",
        CONTRACTS / "enums.json": json.dumps(enums, indent=2, sort_keys=True) + "\n",
    }


def check() -> int:
    stale: list[str] = []
    for path, expected in build().items():
        actual = path.read_text(encoding="utf-8") if path.exists() else ""
        if actual != expected:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        print("STALE contract files (run `python scripts/export_contracts.py`):")
        for name in stale:
            print(f"  - {name}")
        return 1
    print(f"contracts up to date ({len(build())} generated files)")
    return 0


def write() -> int:
    CONTRACTS.mkdir(parents=True, exist_ok=True)
    for path, contents in build().items():
        path.write_text(contents, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if contracts are stale")
    args = parser.parse_args(argv)
    return check() if args.check else write()


if __name__ == "__main__":
    raise SystemExit(main())
